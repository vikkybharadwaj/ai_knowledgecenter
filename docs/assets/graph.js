/* AI Knowledge Center — concept graph (vendor-free, SVG).
   Reads window.KC_DATA (generated by scripts/build-index.py) and renders each
   note as a TITLE CHIP — the label lives *inside* the node, so labels can never
   pile up on top of each other — and each typed connection as a curved, colour-
   coded arrow. Two deterministic layouts (no jittery force-blob):
     - "spine" : the stack layers as labelled horizontal lanes, top→bottom
                 (Foundations → … → Products); order crossing-reduced per lane.
     - "free"  : a force layout run ONCE to convergence, then frozen.
   Hover a chip to trace its connections; drag to rearrange; click to read the
   note in-page (KCReader). Crisp text + automatic light/dark via CSS variables. */
(function () {
  var D = window.KC_DATA;
  if (!D) return;
  var SVGNS = "http://www.w3.org/2000/svg";
  var XHTML = "http://www.w3.org/1999/xhtml";

  var LAYER_COLORS = {
    foundations: "#7aa2f7", api: "#9ece6a", "agent-sdk": "#e0af68",
    "claude-code": "#d98b5f", patterns: "#bb9af7", products: "#f7768e"
  };
  var TYPE_COLORS = {
    "builds-on": "#7aa2f7", enables: "#9ece6a", "part-of": "#d98b5f",
    "used-with": "#bb9af7", "alternative-to": "#e0af68",
    "contrasts-with": "#f7768e", "used-in": "#73daca"
  };
  var TYPE_LABELS = {
    "builds-on": "builds on", enables: "enables", "part-of": "part of",
    "used-with": "used with", "alternative-to": "alternative to",
    "contrasts-with": "contrasts with", "used-in": "used in"
  };

  var svg = document.getElementById("graph");
  if (!svg) return;
  var panel = document.getElementById("node-panel");

  // ---- geometry constants ----
  var GUTTER = 128;   // left lane-label column (spine mode)
  var PAD_R = 22, PAD_T = 22, PAD_B = 22;
  var CHIP_W = 210, CHIP_W_MIN = 130, CHIP_H = 66, CELL_GAP = 18;

  // ---- build node/edge objects ----
  var byId = {};
  var nodes = D.nodes.map(function (n) {
    var o = Object.assign({}, n);
    o.x = 0; o.y = 0; o.vx = 0; o.vy = 0; o.w = CHIP_W; o.h = CHIP_H;
    o.color = LAYER_COLORS[n.layer] || "#9aa5bd";
    o.edges = [];
    byId[n.slug] = o;
    return o;
  });
  var edges = D.edges
    .map(function (e) { return { a: byId[e.from], b: byId[e.to], type: e.type, why: e.why }; })
    .filter(function (e) { return e.a && e.b; });
  edges.forEach(function (e) { e.a.edges.push(e); e.b.edges.push(e); });

  // populated layers in canonical spine order + which types actually occur
  var spineLayers = D.layers.filter(function (l) {
    return nodes.some(function (n) { return n.layer === l; });
  });
  var usedTypes = edges.reduce(function (acc, e) {
    if (acc.indexOf(e.type) === -1) acc.push(e.type); return acc;
  }, []);

  var W = 0, H = 0;
  var layout = "spine";
  var tagFilter = "";
  var hover = null;

  // ---- svg scaffold ----
  svg.setAttribute("xmlns", SVGNS);
  function el(name, attrs) {
    var e = document.createElementNS(SVGNS, name);
    if (attrs) for (var k in attrs) e.setAttribute(k, attrs[k]);
    return e;
  }
  // one arrow marker per connection type, so the head matches the line colour
  var defs = el("defs");
  Object.keys(TYPE_COLORS).forEach(function (t) {
    var m = el("marker", {
      id: "arr-" + t, viewBox: "0 0 10 10", refX: "9", refY: "5",
      markerWidth: "7", markerHeight: "7", orient: "auto-start-reverse"
    });
    m.appendChild(el("path", { d: "M0,0 L10,5 L0,10 z", fill: TYPE_COLORS[t] }));
    defs.appendChild(m);
  });
  svg.appendChild(defs);
  var gLanes = el("g", { class: "kc-lanes" });
  var gEdges = el("g", { class: "kc-edges" });
  var gHover = el("g", { class: "kc-hover" });
  var gNodes = el("g", { class: "kc-nodes" });
  [gLanes, gEdges, gHover, gNodes].forEach(function (g) { svg.appendChild(g); });

  function size() {
    var r = svg.getBoundingClientRect();
    W = Math.max(320, r.width); H = Math.max(360, r.height);
    svg.setAttribute("viewBox", "0 0 " + W + " " + H);
  }

  // ---------- SPINE LAYOUT (deterministic lanes) ----------
  function spineLayout() {
    var lane = {};
    spineLayers.forEach(function (l) {
      lane[l] = nodes.filter(function (n) { return n.layer === l; })
        .sort(function (a, b) { return b.connCount - a.connCount; });
      lane[l].forEach(function (n, i) { n.col = i; });
    });
    // crossing reduction: a few barycenter sweeps over the column index
    for (var pass = 0; pass < 8; pass++) {
      var order = pass % 2 ? spineLayers.slice().reverse() : spineLayers;
      order.forEach(function (l) {
        lane[l].forEach(function (n) {
          var nb = n.edges.map(function (e) { return e.a === n ? e.b : e.a; })
            .filter(function (m) { return m.layer !== l; });
          n.bary = nb.length
            ? nb.reduce(function (s, m) { return s + m.col; }, 0) / nb.length
            : n.col;
        });
        lane[l].sort(function (a, b) { return a.bary - b.bary; });
        lane[l].forEach(function (n, i) { n.col = i; });
      });
    }
    var L = spineLayers.length;
    var laneH = (H - PAD_T - PAD_B) / L;
    var leftX = GUTTER, usableW = W - GUTTER - PAD_R;
    spineLayers.forEach(function (l, li) {
      var ns = lane[l], cells = ns.length, cellW = usableW / cells;
      var cy = PAD_T + laneH * (li + 0.5);
      ns.forEach(function (n) {
        n.w = Math.max(CHIP_W_MIN, Math.min(CHIP_W, cellW - CELL_GAP));
        n.h = CHIP_H;
        n.x = leftX + cellW * (n.col + 0.5);
        n.y = cy;
      });
    });
  }

  // ---------- FREE LAYOUT (force, run once then frozen) ----------
  function freeLayout() {
    nodes.forEach(function (n) {
      n.w = CHIP_W; n.h = CHIP_H;
      if (!isFinite(n.x) || n.x === 0) n.x = W / 2 + Math.cos(n.col || 0) * 60;
      n.vx = 0; n.vy = 0;
    });
    var cx = W / 2, cy = H / 2;
    for (var it = 0; it < 600; it++) {
      for (var i = 0; i < nodes.length; i++) {
        var a = nodes[i];
        for (var j = i + 1; j < nodes.length; j++) {
          var b = nodes[j];
          var dx = a.x - b.x, dy = a.y - b.y;
          var d2 = dx * dx + dy * dy || 1, d = Math.sqrt(d2);
          var f = 12000 / d2, ux = dx / d, uy = dy / d;
          a.vx += ux * f; a.vy += uy * f; b.vx -= ux * f; b.vy -= uy * f;
        }
      }
      edges.forEach(function (e) {
        var dx = e.b.x - e.a.x, dy = e.b.y - e.a.y;
        var d = Math.sqrt(dx * dx + dy * dy) || 1, f = (d - 200) * 0.03;
        var ux = dx / d, uy = dy / d;
        e.a.vx += ux * f; e.a.vy += uy * f; e.b.vx -= ux * f; e.b.vy -= uy * f;
      });
      nodes.forEach(function (n) {
        n.vx += (cx - n.x) * 0.012; n.vy += (cy - n.y) * 0.012;
        n.vx *= 0.84; n.vy *= 0.84; n.x += n.vx; n.y += n.vy;
      });
    }
    for (var p = 0; p < 18; p++) resolveOverlaps();
    nodes.forEach(clampNode);
  }

  function resolveOverlaps() {
    var mx = 16, my = 14;
    for (var i = 0; i < nodes.length; i++) {
      for (var j = i + 1; j < nodes.length; j++) {
        var a = nodes[i], b = nodes[j];
        var ox = (a.w + b.w) / 2 + mx - Math.abs(a.x - b.x);
        var oy = (a.h + b.h) / 2 + my - Math.abs(a.y - b.y);
        if (ox > 0 && oy > 0) {
          if (ox < oy) { var sx = (a.x < b.x ? -1 : 1) * ox / 2; a.x += sx; b.x -= sx; }
          else { var sy = (a.y < b.y ? -1 : 1) * oy / 2; a.y += sy; b.y -= sy; }
        }
      }
    }
  }

  function clampNode(n) {
    n.x = Math.max(PAD_R + n.w / 2, Math.min(W - PAD_R - n.w / 2, n.x));
    n.y = Math.max(PAD_T + n.h / 2, Math.min(H - PAD_B - n.h / 2, n.y));
  }

  function relayout() { layout === "spine" ? spineLayout() : freeLayout(); }

  // ---- edge geometry: trim to chip borders, gentle bow, arrow at the target ----
  function borderPoint(n, towardX, towardY) {
    var dx = towardX - n.x, dy = towardY - n.y;
    if (!dx && !dy) return { x: n.x, y: n.y };
    var hw = n.w / 2 + 2, hh = n.h / 2 + 2;
    var s = 1 / Math.max(Math.abs(dx) / hw, Math.abs(dy) / hh);
    return { x: n.x + dx * s, y: n.y + dy * s };
  }
  function edgePath(e) {
    var p1 = borderPoint(e.a, e.b.x, e.b.y);
    var p2 = borderPoint(e.b, e.a.x, e.a.y);
    var mx = (p1.x + p2.x) / 2, my = (p1.y + p2.y) / 2;
    var dx = p2.x - p1.x, dy = p2.y - p1.y, len = Math.sqrt(dx * dx + dy * dy) || 1;
    var sign = ((e.a.slug.charCodeAt(0) + e.b.slug.charCodeAt(0)) % 2) ? 1 : -1;
    var bow = Math.min(46, len * 0.16) * sign;
    var ctrlX = mx + (-dy / len) * bow, ctrlY = my + (dx / len) * bow;
    return { d: "M" + p1.x + "," + p1.y + " Q" + ctrlX + "," + ctrlY + " " + p2.x + "," + p2.y, mx: ctrlX, my: ctrlY };
  }

  function escapeHtml(s) {
    return String(s).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }

  // ---- render ----
  function render() {
    relayout();
    // lanes (spine only)
    gLanes.textContent = "";
    if (layout === "spine") {
      var L = spineLayers.length, laneH = (H - PAD_T - PAD_B) / L;
      spineLayers.forEach(function (l, li) {
        var top = PAD_T + laneH * li, cy = top + laneH / 2, col = LAYER_COLORS[l] || "#9aa5bd";
        gLanes.appendChild(el("rect", { x: 0, y: top, width: W, height: laneH, class: "kc-band", fill: col, "fill-opacity": li % 2 ? 0.05 : 0.09 }));
        gLanes.appendChild(el("rect", { x: 0, y: top + 7, width: 4, height: laneH - 14, rx: 2, fill: col }));
        gLanes.appendChild(el("circle", { cx: 22, cy: cy - 9, r: 5, fill: col }));
        var name = el("text", { x: 34, y: cy - 5, class: "kc-lane-name" });
        name.textContent = D.layerLabels[l] || l;
        var cnt = nodes.filter(function (n) { return n.layer === l; }).length;
        var sub = el("text", { x: 34, y: cy + 12, class: "kc-lane-sub" });
        sub.textContent = cnt + (cnt === 1 ? " note" : " notes");
        gLanes.appendChild(name); gLanes.appendChild(sub);
      });
    }
    // edges
    gEdges.textContent = "";
    edges.forEach(function (e) {
      var path = el("path", {
        d: edgePath(e).d, class: "kc-edge", fill: "none",
        stroke: TYPE_COLORS[e.type] || "#5a637a", "marker-end": "url(#arr-" + e.type + ")"
      });
      e.el = path; gEdges.appendChild(path);
    });
    // nodes (chips)
    gNodes.textContent = "";
    nodes.forEach(function (n) {
      var fo = el("foreignObject", { x: n.x - n.w / 2, y: n.y - n.h / 2, width: n.w, height: n.h, class: "kc-fo" });
      var cls = "kc-node" + (n.connCount >= 7 ? " hub" : "") + (n.kind === "scenario" ? " scenario" : "");
      fo.innerHTML =
        '<div xmlns="' + XHTML + '" class="' + cls + '" data-slug="' + n.slug + '" ' +
        'style="border-left-color:' + n.color + '" title="' + escapeHtml(n.title) + '">' +
        '<span class="kc-dot" style="background:' + n.color + '"></span>' +
        '<span class="kc-title">' + escapeHtml(n.title) + '</span>' +
        '<span class="kc-badge" title="' + n.connCount + ' connections">' + n.connCount + '</span>' +
        '</div>';
      n.fo = fo; n.div = fo.firstChild; wire(n); gNodes.appendChild(fo);
    });
    applyState();
  }

  function updateGeom(list) {
    (list || edges).forEach(function (e) { if (e.el) e.el.setAttribute("d", edgePath(e).d); });
  }
  function moveChip(n) {
    n.fo.setAttribute("x", n.x - n.w / 2);
    n.fo.setAttribute("y", n.y - n.h / 2);
  }

  // ---- visual state: hover focus + tag filter ----
  function neighborsOf(n) {
    var set = {}; set[n.slug] = true;
    n.edges.forEach(function (e) { set[e.a.slug] = true; set[e.b.slug] = true; });
    return set;
  }
  function visible(n) { return !tagFilter || (n.tags || []).indexOf(tagFilter) !== -1; }
  function applyState() {
    var lit = hover ? neighborsOf(hover) : null;
    nodes.forEach(function (n) {
      var dim = (tagFilter && !visible(n)) || (lit && !lit[n.slug]);
      n.div.classList.toggle("dim", !!dim);
      n.div.classList.toggle("lit", !!(lit && lit[n.slug] && n !== hover));
    });
    edges.forEach(function (e) {
      if (!e.el) return;
      var on = hover && (e.a === hover || e.b === hover);
      var tagDim = tagFilter && !(visible(e.a) && visible(e.b));
      e.el.classList.toggle("on", !!on);
      e.el.classList.toggle("dim", !!((hover && !on) || tagDim));
    });
    gHover.textContent = "";
    if (hover) {
      hover.edges.forEach(function (e) {
        var g = edgePath(e);
        var t = el("text", { x: g.mx, y: g.my - 2, class: "kc-etype", fill: TYPE_COLORS[e.type] || "#9aa5bd" });
        t.textContent = TYPE_LABELS[e.type] || e.type;
        gHover.appendChild(t);
      });
    }
  }

  // ---- interaction: hover, drag, click ----
  var drag = null, dragMoved = false, startPt = null;
  function svgPt(ev) {
    var r = svg.getBoundingClientRect();
    return { x: ev.clientX - r.left, y: ev.clientY - r.top };
  }
  function wire(n) {
    var d = n.div;
    d.addEventListener("mouseenter", function () { if (!drag) { hover = n; applyState(); } });
    d.addEventListener("mouseleave", function () { if (!drag) { hover = null; applyState(); } });
    d.addEventListener("pointerdown", function (ev) {
      drag = n; dragMoved = false; startPt = svgPt(ev);
      try { d.setPointerCapture(ev.pointerId); } catch (e) {}
      d.classList.add("grabbing");
    });
    d.addEventListener("pointermove", function (ev) {
      if (drag !== n) return;
      var p = svgPt(ev);
      if (Math.abs(p.x - startPt.x) > 3 || Math.abs(p.y - startPt.y) > 3) dragMoved = true;
      n.x = p.x; n.y = p.y; clampNode(n);
      moveChip(n); updateGeom(n.edges);
      if (hover === n) applyState();
    });
    d.addEventListener("pointerup", function (ev) {
      if (drag !== n) return;
      try { d.releasePointerCapture(ev.pointerId); } catch (e) {}
      d.classList.remove("grabbing"); drag = null;
      if (!dragMoved) showPanel(n);
    });
  }

  function showPanel(n) {
    if (!panel) { if (window.KCReader) window.KCReader.open(n.slug); return; }
    var outs = edges.filter(function (e) { return e.a === n; }).map(function (e) {
      return "<li><span class='etype' style='color:" + (TYPE_COLORS[e.type] || "#9aa5bd") + "'>" + (TYPE_LABELS[e.type] || e.type) +
        "</span> → <strong>" + escapeHtml(e.b.title) + "</strong>" + (e.why ? "<br><span class='ewhy'>" + escapeHtml(e.why) + "</span>" : "") + "</li>";
    });
    var ins = edges.filter(function (e) { return e.b === n; }).map(function (e) {
      return "<li><strong>" + escapeHtml(e.a.title) + "</strong> <span class='etype' style='color:" + (TYPE_COLORS[e.type] || "#9aa5bd") + "'>" + (TYPE_LABELS[e.type] || e.type) + "</span> → this</li>";
    });
    panel.innerHTML =
      "<button class='np-close' type='button' aria-label='Close'>✕</button>" +
      "<div class='np-head'><span class='np-layer' style='background:" + n.color + "'>" + (D.layerLabels[n.layer] || n.layer) + "</span>" +
      "<span class='np-depth'>" + n.depth + "</span></div>" +
      "<h3>" + escapeHtml(n.title) + "</h3>" +
      "<div class='np-tags'>" + (n.tags || []).map(function (t) { return "<span>#" + escapeHtml(t) + "</span>"; }).join(" ") + "</div>" +
      (outs.length ? "<div class='np-sec'>Connects out</div><ul>" + outs.join("") + "</ul>" : "") +
      (ins.length ? "<div class='np-sec'>Connected from</div><ul>" + ins.join("") + "</ul>" : "") +
      "<a class='np-open kc-link' href='#' data-slug='" + n.slug + "'>Read the full note →</a>";
    panel.classList.add("show");
    var cl = panel.querySelector(".np-close");
    if (cl) cl.addEventListener("click", function () { panel.classList.remove("show"); hover = null; applyState(); });
    hover = n; applyState();
  }

  // ---- controls ----
  var layoutBtn = document.getElementById("layout-toggle");
  if (layoutBtn) {
    layoutBtn.textContent = "Layout: Spine ▾";
    layoutBtn.addEventListener("click", function () {
      layout = layout === "spine" ? "free" : "spine";
      layoutBtn.textContent = layout === "spine" ? "Layout: Spine ▾" : "Layout: Free ▾";
      hover = null; render();
    });
  }
  var tagSel = document.getElementById("tag-filter");
  if (tagSel) {
    var tags = {};
    nodes.forEach(function (n) { (n.tags || []).forEach(function (t) { tags[t] = (tags[t] || 0) + 1; }); });
    Object.keys(tags).sort().forEach(function (t) {
      var o = document.createElement("option");
      o.value = t; o.textContent = "#" + t + " (" + tags[t] + ")"; tagSel.appendChild(o);
    });
    tagSel.addEventListener("change", function () { tagFilter = tagSel.value; applyState(); });
  }

  // ---- legends: stack layers (left) + connection types (under graph) ----
  var legend = document.getElementById("legend");
  if (legend) {
    legend.innerHTML = D.layers.map(function (l) {
      return "<span class='lg'><i style='background:" + (LAYER_COLORS[l] || "#9aa5bd") + "'></i>" + (D.layerLabels[l] || l) + "</span>";
    }).join("");
  }
  var graphWrap = svg.closest(".graph-wrap");
  if (graphWrap && usedTypes.length) {
    var key = document.createElement("div");
    key.className = "kc-edgekey";
    key.innerHTML = "<span class='kc-edgekey-h'>connection&nbsp;types</span>" + usedTypes.map(function (t) {
      return "<span class='ek'><i style='background:" + (TYPE_COLORS[t] || "#9aa5bd") + "'></i>" + (TYPE_LABELS[t] || t) + "</span>";
    }).join("");
    graphWrap.insertAdjacentElement("afterend", key);
  }

  // ---- boot ----
  var rtid = null;
  window.addEventListener("resize", function () {
    clearTimeout(rtid);
    rtid = setTimeout(function () { size(); render(); }, 120);
  });
  size();
  render();
})();
