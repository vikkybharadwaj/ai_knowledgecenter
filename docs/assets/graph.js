/* AI Knowledge Center — concept graph (vendor-free, canvas force layout).
   Reads window.KC_DATA (generated by scripts/build-index.py) and renders the
   notes as nodes and their typed connections as edges. Two layouts:
     - "free"  : force-directed (repulsion + edge springs + gravity)
     - "spine" : layered bands by spine_layer (Foundations → Products)
   Hover a node to light up its connections; click to read its note in-page. */
(function () {
  var D = window.KC_DATA;
  if (!D) return;

  var LAYER_COLORS = {
    foundations: "#7aa2f7", api: "#9ece6a", "agent-sdk": "#e0af68",
    "claude-code": "#d98b5f", patterns: "#bb9af7", products: "#f7768e"
  };
  var TYPE_COLORS = {
    "builds-on": "#7aa2f7", enables: "#9ece6a", "part-of": "#d98b5f",
    "used-with": "#bb9af7", "alternative-to": "#e0af68",
    "contrasts-with": "#f7768e", "used-in": "#73daca"
  };

  var canvas = document.getElementById("graph");
  if (!canvas) return;
  var ctx = canvas.getContext("2d");
  var panel = document.getElementById("node-panel");

  // ---- build node/edge objects ----
  var byId = {};
  var nodes = D.nodes.map(function (n, i) {
    var o = Object.assign({}, n);
    o.x = Math.cos(i) * 180 + (i % 5) * 12;
    o.y = Math.sin(i) * 140 + (i % 3) * 12;
    o.vx = 0; o.vy = 0;
    o.r = 9 + Math.min(14, (n.connCount || 0) * 2.2);
    o.color = LAYER_COLORS[n.layer] || "#9aa5bd";
    byId[n.slug] = o;
    return o;
  });
  var edges = D.edges
    .map(function (e) { return { a: byId[e.from], b: byId[e.to], type: e.type, why: e.why }; })
    .filter(function (e) { return e.a && e.b; });

  var W = 0, H = 0, DPR = Math.max(1, window.devicePixelRatio || 1);
  var layout = "spine";       // "spine" | "free"
  var tagFilter = "";
  var hover = null, dragging = null, dragMoved = false;

  function size() {
    var rect = canvas.getBoundingClientRect();
    W = rect.width; H = rect.height;
    canvas.width = W * DPR; canvas.height = H * DPR;
    ctx.setTransform(DPR, 0, 0, DPR, 0, 0);
  }
  window.addEventListener("resize", function () { size(); seed(); });

  function layerY(layer) {
    var i = D.layers.indexOf(layer);
    if (i < 0) i = D.layers.length - 1;
    var pad = 64;
    return pad + (H - 2 * pad) * (i / (D.layers.length - 1));
  }

  function seed() {
    nodes.forEach(function (n, i) {
      if (layout === "spine") {
        n.ty = layerY(n.layer);
        // spread x by index within its layer
        var peers = nodes.filter(function (m) { return m.layer === n.layer; });
        var k = peers.indexOf(n);
        n.x = W * (0.12 + 0.76 * (peers.length === 1 ? 0.5 : k / (peers.length - 1)));
        n.y = n.ty;
      } else {
        if (!isFinite(n.x)) n.x = W / 2;
        n.ty = null;
      }
    });
  }

  function visible(n) {
    return !tagFilter || (n.tags || []).indexOf(tagFilter) !== -1;
  }

  // ---- physics ----
  function step() {
    var k = 0.012;
    for (var i = 0; i < nodes.length; i++) {
      var a = nodes[i];
      if (a === dragging) continue;
      // repulsion
      for (var j = i + 1; j < nodes.length; j++) {
        var b = nodes[j];
        var dx = a.x - b.x, dy = a.y - b.y;
        var d2 = dx * dx + dy * dy || 1;
        var f = 2600 / d2;
        var d = Math.sqrt(d2);
        var ux = dx / d, uy = dy / d;
        a.vx += ux * f; a.vy += uy * f;
        if (b !== dragging) { b.vx -= ux * f; b.vy -= uy * f; }
      }
    }
    // springs
    edges.forEach(function (e) {
      var dx = e.b.x - e.a.x, dy = e.b.y - e.a.y;
      var d = Math.sqrt(dx * dx + dy * dy) || 1;
      var rest = 132;
      var f = (d - rest) * 0.02;
      var ux = dx / d, uy = dy / d;
      if (e.a !== dragging) { e.a.vx += ux * f; e.a.vy += uy * f; }
      if (e.b !== dragging) { e.b.vx -= ux * f; e.b.vy -= uy * f; }
    });
    nodes.forEach(function (n) {
      if (n === dragging) return;
      if (layout === "spine") {
        n.vy += (n.ty - n.y) * 0.12;      // strong pull to layer band
        n.vx += (W / 2 - n.x) * 0.0006;
      } else {
        n.vx += (W / 2 - n.x) * k * 0.5;
        n.vy += (H / 2 - n.y) * k * 0.5;
      }
      n.vx *= 0.86; n.vy *= 0.86;
      n.x += n.vx; n.y += n.vy;
      var m = 28;
      n.x = Math.max(m, Math.min(W - m, n.x));
      n.y = Math.max(m, Math.min(H - m, n.y));
    });
  }

  function themeText() {
    return document.documentElement.getAttribute("data-theme") === "light" ? "#1a1e29" : "#e6e9f0";
  }

  function draw() {
    ctx.clearRect(0, 0, W, H);
    var hl = hover;
    var connected = {};
    if (hl) {
      connected[hl.slug] = true;
      edges.forEach(function (e) {
        if (e.a === hl) connected[e.b.slug] = true;
        if (e.b === hl) connected[e.a.slug] = true;
      });
    }
    // edges
    edges.forEach(function (e) {
      var dim = (tagFilter && !(visible(e.a) && visible(e.b))) ||
                (hl && e.a !== hl && e.b !== hl);
      ctx.globalAlpha = dim ? 0.07 : (hl ? 0.9 : 0.34);
      ctx.strokeStyle = TYPE_COLORS[e.type] || "#5a637a";
      ctx.lineWidth = (hl && (e.a === hl || e.b === hl)) ? 2.2 : 1.1;
      ctx.beginPath(); ctx.moveTo(e.a.x, e.a.y); ctx.lineTo(e.b.x, e.b.y); ctx.stroke();
      // edge type label when relevant
      if (hl && (e.a === hl || e.b === hl)) {
        ctx.globalAlpha = 0.95;
        ctx.fillStyle = TYPE_COLORS[e.type] || "#9aa5bd";
        ctx.font = "10px ui-monospace, monospace";
        ctx.textAlign = "center";
        ctx.fillText(e.type, (e.a.x + e.b.x) / 2, (e.a.y + e.b.y) / 2 - 3);
      }
    });
    // nodes
    ctx.globalAlpha = 1;
    nodes.forEach(function (n) {
      var dim = (tagFilter && !visible(n)) || (hl && !connected[n.slug]);
      ctx.globalAlpha = dim ? 0.22 : 1;
      ctx.beginPath();
      ctx.arc(n.x, n.y, n.r, 0, 6.2832);
      ctx.fillStyle = n.color;
      ctx.fill();
      if (n.kind === "scenario") { ctx.lineWidth = 2; ctx.strokeStyle = "#fff"; ctx.stroke(); }
      if (n === hl) { ctx.lineWidth = 3; ctx.strokeStyle = themeText(); ctx.stroke(); }
      // label
      ctx.globalAlpha = dim ? 0.25 : 1;
      ctx.fillStyle = themeText();
      ctx.font = (n === hl ? "600 " : "") + "12px var(--sans), -apple-system, sans-serif";
      ctx.textAlign = "center"; ctx.textBaseline = "top";
      var label = n.title.length > 30 ? n.title.slice(0, 28) + "…" : n.title;
      ctx.fillText(label, n.x, n.y + n.r + 3);
    });
    ctx.globalAlpha = 1;
  }

  function frame() { step(); draw(); requestAnimationFrame(frame); }

  // ---- picking & interaction ----
  function nodeAt(mx, my) {
    for (var i = nodes.length - 1; i >= 0; i--) {
      var n = nodes[i];
      if ((tagFilter && !visible(n))) continue;
      var dx = mx - n.x, dy = my - n.y;
      if (dx * dx + dy * dy <= (n.r + 6) * (n.r + 6)) return n;
    }
    return null;
  }
  function pos(ev) {
    var r = canvas.getBoundingClientRect();
    return { x: ev.clientX - r.left, y: ev.clientY - r.top };
  }
  canvas.addEventListener("mousemove", function (ev) {
    var p = pos(ev);
    if (dragging) { dragging.x = p.x; dragging.y = p.y; dragging.vx = dragging.vy = 0; dragMoved = true; }
    else { hover = nodeAt(p.x, p.y); canvas.style.cursor = hover ? "pointer" : "default"; }
  });
  canvas.addEventListener("mousedown", function (ev) {
    var p = pos(ev); dragging = nodeAt(p.x, p.y); dragMoved = false;
  });
  window.addEventListener("mouseup", function () {
    if (dragging && !dragMoved) showPanel(dragging);
    dragging = null;
  });
  canvas.addEventListener("mouseleave", function () { hover = null; });

  function showPanel(n) {
    if (!panel) { if (window.KCReader) window.KCReader.open(n.slug); return; }
    hover = n;
    var outs = edges.filter(function (e) { return e.a === n; })
      .map(function (e) { return "<li><span class='etype' style='color:" + (TYPE_COLORS[e.type] || "#9aa5bd") + "'>" + e.type + "</span> → <strong>" + byId[e.b.slug].title + "</strong><br><span class='ewhy'>" + (e.why || "") + "</span></li>"; });
    var ins = edges.filter(function (e) { return e.b === n; })
      .map(function (e) { return "<li><strong>" + byId[e.a.slug].title + "</strong> <span class='etype' style='color:" + (TYPE_COLORS[e.type] || "#9aa5bd") + "'>" + e.type + "</span> → this</li>"; });
    panel.innerHTML =
      "<div class='np-head'><span class='np-layer' style='background:" + n.color + "'>" + (D.layerLabels[n.layer] || n.layer) + "</span>" +
      "<span class='np-depth'>" + n.depth + "</span></div>" +
      "<h3>" + n.title + "</h3>" +
      "<div class='np-tags'>" + (n.tags || []).map(function (t) { return "<span>#" + t + "</span>"; }).join(" ") + "</div>" +
      (outs.length ? "<div class='np-sec'>Connects out</div><ul>" + outs.join("") + "</ul>" : "") +
      (ins.length ? "<div class='np-sec'>Connected from</div><ul>" + ins.join("") + "</ul>" : "") +
      "<a class='np-open kc-link' href='#' data-slug='" + n.slug + "'>Read the full note →</a>";
    panel.classList.add("show");
  }

  // ---- controls ----
  var layoutBtn = document.getElementById("layout-toggle");
  if (layoutBtn) layoutBtn.addEventListener("click", function () {
    layout = layout === "spine" ? "free" : "spine";
    layoutBtn.textContent = layout === "spine" ? "Layout: Spine ▾" : "Layout: Free ▾";
    seed();
  });
  var tagSel = document.getElementById("tag-filter");
  if (tagSel) {
    var tags = {};
    nodes.forEach(function (n) { (n.tags || []).forEach(function (t) { tags[t] = (tags[t] || 0) + 1; }); });
    Object.keys(tags).sort().forEach(function (t) {
      var o = document.createElement("option"); o.value = t; o.textContent = "#" + t + " (" + tags[t] + ")"; tagSel.appendChild(o);
    });
    tagSel.addEventListener("change", function () { tagFilter = tagSel.value; });
  }

  // ---- legend ----
  var legend = document.getElementById("legend");
  if (legend) {
    legend.innerHTML = D.layers.map(function (l) {
      return "<span class='lg'><i style='background:" + (LAYER_COLORS[l] || "#9aa5bd") + "'></i>" + (D.layerLabels[l] || l) + "</span>";
    }).join("");
  }

  size(); seed(); frame();
})();
